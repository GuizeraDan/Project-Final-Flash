const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--autoplay-policy=no-user-gesture-required'] });
  const ctx = await b.newContext({ viewport: { width: 1366, height: 768 } });
  await ctx.route('https://api.github.com/**', r => r.abort());
  const p = await ctx.newPage();
  const erros = []; const vig = (pg) => { pg.on('pageerror', e => erros.push(e.message)); pg.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') erros.push(m.text()); }); }; vig(p);
  const ok = (c, m) => console.log((c ? 'ok: ' : 'FALHOU: ') + m);
  await p.goto('file://' + require('path').resolve(__dirname, '..', '..') + '/estudio.html?aba=golpes&personagem=krillin&golpe=kamehameha');
  await p.waitForFunction(() => FF.Estudio.pronto && FF.Estudio.Golpes && FF.Estudio.Golpes.doc && FF.Estudio.Golpes.doc.origem.id === 'kamehameha', null, { timeout: 30000 });
  await p.click('text=＋ Novo');
  await p.waitForTimeout(300);
  await p.evaluate(() => { const G = FF.Estudio.Golpes; G.adicionar('efeitos', 0.3); });
  await p.waitForTimeout(300);
  // abre o seletor pelo botão 🖼 do campo Efeito
  await p.locator('.es-campo', { hasText: 'Efeito' }).first().locator('button:has-text("🖼")').click();
  await p.waitForSelector('.es-seletor .es-cartao', { timeout: 15000 });
  await p.screenshot({ path: require('os').tmpdir() + '/ff_sel1.png' });
  await p.fill('.es-seletor input[type=search]', 'Bills_Esfera');
  await p.waitForTimeout(800);
  await p.screenshot({ path: require('os').tmpdir() + '/ff_sel2.png' });
  await p.locator('.es-seletor .es-cartao', { hasText: 'Bills_Esfera' }).first().click();
  const ef = await p.evaluate(() => FF.Estudio.Golpes.clipe());
  ok(ef.fx.startsWith('Bills_Esfera') && ef.sprite === 'bills', 'efeito do Bills no golpe do Kuririn: ' + ef.fx + ' / ' + ef.sprite);
  // animação emprestada: Kuririn com uma animação do Bills
  await p.evaluate(() => { const G = FF.Estudio.Golpes; const tr = G.doc.linha.trilhas.find(t => t.id === 'atacante'); G.selecionar(tr.clipes[0].id, 'atacante'); });
  await p.waitForTimeout(300);
  await p.locator('.es-campo', { hasText: 'Animação' }).first().locator('button:has-text("🖼")').click();
  await p.waitForSelector('.es-seletor .es-seletor-fonte');
  await p.click('.es-seletor .es-seletor-fonte[data-fonte="bills"]');
  await p.waitForTimeout(800);
  await p.screenshot({ path: require('os').tmpdir() + '/ff_sel3.png' });
  await p.locator('.es-seletor .es-cartao').nth(2).click();
  const an = await p.evaluate(() => FF.Estudio.Golpes.clipe());
  ok(an.sprite === 'bills', 'animação emprestada do Bills: ' + an.anim);
  await p.evaluate(() => FF.Estudio.Golpes.irPara(0.2));
  ok(await p.evaluate(() => FF.Estudio.Golpes.palco._b.atk.sprite === FF.Assets.sprites.bills), 'no palco o Kuririn desenha com o sprite do Bills');
  await p.evaluate(() => FF.Estudio.Golpes.irPara(5));
  ok(await p.evaluate(() => FF.Estudio.Golpes.palco._b.atk.sprite === FF.Assets.sprites.krillin), 'no fim volta ao sprite dele');
  await p.screenshot({ path: require('os').tmpdir() + '/ff_sel4.png' });
  await p.evaluate(() => { FF.Estudio.Golpes.doc.golpe.nome = 'Teste Bills'; FF.Estudio.Golpes.salvar(); });
  const h = await p.evaluate(() => Object.values(FF.Habilidades.ler()).find(h => h.nome === 'Teste Bills'));
  ok(h && (h.golpe.spritesUsados || []).includes('bills'), 'golpe salvo lista os sprites usados: ' + JSON.stringify(h && h.golpe.spritesUsados));
  // jogo
  const g = await ctx.newPage(); vig(g);
  await g.goto('file://' + require('path').resolve(__dirname, '..', '..') + '/index.html');
  await g.evaluate(() => sessionStorage.setItem('ff_livre_def', JSON.stringify({ id: 'livre', saga: 'livre', titulo: 'T', cenario: 'campo', musica: 'tournament_theme', escala: 2.5, posicoes: { herois: [170], inimigos: [915] }, herois: ['krillin'], inimigos: ['raditz'], ajustes: {} })));
  await g.goto('file://' + require('path').resolve(__dirname, '..', '..') + '/index.html?livre=1');
  await g.waitForFunction(() => document.querySelector('#menu').classList.contains('open'), null, { timeout: 40000 });
  ok(await g.evaluate(() => !!FF.Assets.sprites.bills), 'batalha carregou o sprite do Bills');
  const nomes = await g.$$eval('#menu .cmd-golpes button .nome', l => l.map(x => x.textContent));
  const i = nomes.findIndex(n => n.includes('Teste Bills'));
  const hp0 = await g.evaluate(() => FF.battle.enemies[0].hp);
  await g.click('#menu .cmd-golpes button >> nth=' + i);
  await g.waitForTimeout(700);
  await g.screenshot({ path: require('os').tmpdir() + '/ff_sel5.png' });
  await g.waitForFunction(() => !FF.battle.heroes[0].busy, null, { timeout: 15000 });
  ok(await g.evaluate((h) => FF.battle.enemies[0].hp < h && FF.battle.heroes[0].sprite === FF.Assets.sprites.krillin, hp0), 'golpe rodou na batalha e o Kuririn voltou ao sprite dele');
  ok(!erros.length, 'console: ' + erros.join(' | '));
  await b.close();
})();
